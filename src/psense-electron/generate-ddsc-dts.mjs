/**
 * Generates ddsc-table.d.ts from ddsc-table.json.
 *
 * The vendored renderer consults window.ddsc.<module>.<func>; the table
 * (extracted from the Windows vendor app) lists every function name per
 * module. This generator types each module as a tuple of literal names
 * so preload.ts and (later) backend.ts stop needing `any` where the
 * contract is actually static data.
 *
 * Run: cd src/psense-electron && bun run generate:ddsc
 */

import { readFileSync, writeFileSync } from "node:fs";

const table = JSON.parse(
    readFileSync(new URL("./ddsc-table.json", import.meta.url), "utf8"),
);

const moduleKeys = Object.keys(table);
if (moduleKeys.length === 0) throw new Error("ddsc-table.json: no modules");
for (const key of moduleKeys) {
    const fns = table[key];
    if (!Array.isArray(fns) || fns.length === 0) {
        throw new Error(`ddsc-table.json.${key}: must be a non-empty list of names`);
    }
}

const lines = [
    "/** GENERATED by tools/generate-ddsc-dts.mjs from ddsc-table.json - do not edit by hand.",
    " *  Regenerate: cd src/psense-electron && bun run generate:ddsc",
    " */",
    "",
    "type DdscTable = {",
];
for (const key of moduleKeys) {
    const fns = table[key];
    lines.push(`    ${JSON.stringify(key)}: [`);
    for (const fn of fns) lines.push(`        ${JSON.stringify(fn)},`);
    lines.push("    ];");
}
lines.push("};");
lines.push("");
lines.push('declare module "./ddsc-table.json" {');
lines.push("    const value: DdscTable;");
lines.push("    export = value;");
lines.push("}");
lines.push("");

const total = moduleKeys.reduce((n, k) => n + table[k].length, 0);
writeFileSync(new URL("./ddsc-table.d.ts", import.meta.url), lines.join("\n"));
console.log(`generated ddsc-table.d.ts: ${moduleKeys.length} modules, ${total} functions`);
